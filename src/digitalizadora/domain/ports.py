from collections.abc import Sequence
from datetime import datetime
from pathlib import Path
from typing import Protocol

from digitalizadora.domain.application_settings import ApplicationSettings
from digitalizadora.domain.documents.document_draft import DocumentDraft, DocumentPageFiles
from digitalizadora.domain.documents.document_draft_reconciliation import DraftFileInventory
from digitalizadora.domain.documents.document_pdf_to_save import DocumentPdfToSave
from digitalizadora.domain.encoded_scan import EncodedScan
from digitalizadora.domain.quick_scan.last_scan import QuickScanMasterFiles, QuickScanSlot, SavedScanFile
from digitalizadora.domain.scan_result import ScanResult
from digitalizadora.domain.scan_settings import ScanSettings
from digitalizadora.domain.scanned_image import ScannedImage
from digitalizadora.domain.scanner_capabilities import ScannerCapabilities
from digitalizadora.domain.scanner_endpoint import ScannerEndpoint
from digitalizadora.domain.scanner_status import ScannerStatus


class Clock(Protocol):
    def now(self) -> datetime: ...

    def now_in_nanoseconds(self) -> int: ...


class ScannerGateway(Protocol):
    async def read_capabilities(self) -> ScannerCapabilities: ...

    async def read_status(self) -> ScannerStatus: ...

    async def scan_page(self, settings: ScanSettings) -> ScannedImage: ...


class ScannerGatewayProvider(Protocol):
    async def acquire_gateway(self) -> ScannerGateway: ...


class ScannerDiscovery(Protocol):
    async def discover(self, timeout_seconds: float) -> list[ScannerEndpoint]: ...


class ScannerEndpointRepository(Protocol):
    def load(self) -> ScannerEndpoint | None: ...

    def save(self, endpoint: ScannerEndpoint) -> None: ...

    def clear(self) -> None: ...


class ApplicationSettingsRepository(Protocol):
    def load(self) -> ApplicationSettings: ...

    def save(self, settings: ApplicationSettings) -> None: ...


class ScanOutputRepository(Protocol):
    def output_folder(self) -> Path: ...

    def ensure_output_folder_ready(self) -> None: ...

    def save_scans(self, encoded_scans: Sequence[EncodedScan]) -> tuple[Path, ...]: ...

    def save_scans_in_folder(self, output_folder: Path, encoded_scans: Sequence[EncodedScan]) -> tuple[Path, ...]: ...

    def save_document(self, document_pdf: DocumentPdfToSave) -> ScanResult: ...

    def describe_saved_scan(self, scan_path: Path) -> SavedScanFile | None: ...


class QuickScanSlotRepository(Protocol):
    def storage_folder(self) -> Path: ...

    def ensure_storage_folder_ready(self) -> None: ...

    def write_master_files(self, master_files: QuickScanMasterFiles) -> None: ...

    def master_file_path(self, scan_identifier: str) -> Path: ...

    def read_thumbnail(self, scan_identifier: str) -> bytes | None: ...

    def load(self) -> QuickScanSlot | None: ...

    def commit(self, slot: QuickScanSlot) -> None: ...

    def delete_leftovers(self, kept_scan_identifier: str | None) -> None: ...

    def discard(self) -> None: ...


class DocumentDraftRepository(Protocol):
    def storage_folder(self) -> Path: ...

    def claim_exclusive_access(self) -> None: ...

    def ensure_storage_folder_ready(self) -> None: ...

    def load_manifest(self) -> DocumentDraft | None: ...

    def save_manifest(self, draft: DocumentDraft) -> None: ...

    def ensure_draft_folder_exists(self) -> None: ...

    def write_page_files(self, page_files: DocumentPageFiles) -> None: ...

    def page_file_path(self, page_identifier: str) -> Path: ...

    def page_file_size(self, page_identifier: str) -> int | None: ...

    def read_page_file(self, page_identifier: str) -> bytes | None: ...

    def read_thumbnail(self, page_identifier: str) -> bytes | None: ...

    def delete_page_files(self, page_identifier: str) -> None: ...

    def take_inventory(self) -> DraftFileInventory: ...

    def delete_files(self, file_names: Sequence[str]) -> None: ...

    def set_aside_files(self, file_names: Sequence[str]) -> Path: ...

    def set_aside_draft_folder(self) -> Path | None: ...

    def delete_draft(self) -> None: ...

    def finished_document_exists(self, finished_document_path: Path) -> bool: ...
